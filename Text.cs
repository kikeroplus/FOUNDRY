// 文字。ESP32 版と同じ 6x8 の点の文字 (Adafruit GFX の classic 5x7) を、Scale2x・Scale3x でなめらかに拡大して 3 倍の点で描く。
// 大きさ: 1 = 6x8 (世界の座標)、3 = 12x16、5 = 18x24 (ESP32 版の txt と同じ)。縁に黒いふちと影をつける
using System;
using System.Collections.Generic;

namespace Foundry
