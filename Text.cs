    class Glyph
    {
      public int W, H;      // 点の数
      public bool[] Fill;   // 文字
      public bool[] Ink;    // ふちと影
      public int Pad;       // Ink の外側の余白
    }
    static readonly Dictionary<int, Glyph> cache = new Dictionary<int, Glyph>();

    // 大きさ (1・3・5) → 字の 1 点の大きさ (世界の座標)
    public static int Dot(int size) { return size >= 5 ? 3 : size >= 3 ? 2 : 1; }
    public static int Width(string s, int size) { return s.Length * 6 * Dot(size); }

    static bool[] Base(int ch, out int w, out int h)
    {
      w = 8;
      h = 10; // 1 点ずつ余白をつける (拡大で角がなめらかになるように)
      bool[] m = new bool[w * h];
      if (ch < 32 || ch > 127)
        return m;
      int b = (ch - 32) * 5;
      for (int col = 0; col < 5; col++)
      {
        int line = Font[b + col];
        for (int row = 0; row < 8; row++)
          if ((line >> row & 1) != 0)
            m[(row + 1) * w + col + 1] = true;
      }
      return m;
    }

    static bool At(bool[] m, int w, int h, int x, int y) { return x >= 0 && y >= 0 && x < w && y < h && m[y * w + x]; }

    // 点をそのまま k 倍にして、斜めにつながる所だけ三角に埋める (角はそのまま。D と O が見分けられる)
    static bool[] Upscale(bool[] m, int w, int h, int k)
    {
      int ow = w * k;
      bool[] o = new bool[ow * h * k];
      for (int y = 0; y < h; y++)
        for (int x = 0; x < w; x++)
          if (m[y * w + x])
            for (int ly = 0; ly < k; ly++)
              for (int lx = 0; lx < k; lx++)
                o[(y * k + ly) * ow + x * k + lx] = true;
      float half = k / 2f;
      for (int y = 0; y + 1 < h; y++)
        for (int x = 0; x + 1 < w; x++)
        {
          bool a = At(m, w, h, x, y), b = At(m, w, h, x + 1, y), c = At(m, w, h, x, y + 1), d = At(m, w, h, x + 1, y + 1);
          for (int ly = 0; ly < k; ly++)
            for (int lx = 0; lx < k; lx++)
            {
              if (a && d && !b && !c)
              {
                if (lx + (k - 1 - ly) < half) // 右上のます: 左下の角
                  o[(y * k + ly) * ow + (x + 1) * k + lx] = true;
                if ((k - 1 - lx) + ly < half) // 左下のます: 右上の角
                  o[((y + 1) * k + ly) * ow + x * k + lx] = true;
              }
              if (b && c && !a && !d)
              {
                if ((k - 1 - lx) + (k - 1 - ly) < half) // 左上のます: 右下の角
                  o[(y * k + ly) * ow + x * k + lx] = true;
                if (lx + ly < half) // 右下のます: 左上の角
                  o[((y + 1) * k + ly) * ow + (x + 1) * k + lx] = true;
              }
            }
        }
      return o;
    }

    static Glyph Get(int ch, int dot)
    {
      int key = ch * 8 + dot;
      Glyph g;
      if (cache.TryGetValue(key, out g))
        return g;
      int w, h, k = dot * D.S;
      bool[] m = Upscale(Base(ch, out w, out h), w, h, k);
      w *= k;
      h *= k;
      // ふち (2 点) と、右下への影
      int pad = 2 + dot * 2, ow = w + pad * 2, oh = h + pad * 2, sh = dot + 1;
      bool[] fill = new bool[ow * oh], ink = new bool[ow * oh];
      for (int y = 0; y < h; y++)
        for (int x = 0; x < w; x++)
          if (m[y * w + x])
          {
            fill[(y + pad) * ow + x + pad] = true;
            for (int dy = -2; dy <= 2; dy++)
              for (int dx = -2; dx <= 2; dx++)
                if (Math.Abs(dx) + Math.Abs(dy) <= 3)
                  ink[(y + pad + dy) * ow + x + pad + dx] = true;
            for (int q = 1; q <= sh; q++)
              ink[(y + pad + q + 1) * ow + x + pad + q + 1] = true;
          }
      g = new Glyph();
      g.W = ow;
      g.H = oh;
      g.Fill = fill;
      g.Ink = ink;
      g.Pad = pad;
      cache[key] = g;
      return g;
    }

    // x・y は世界の座標 (左上。center なら x が真ん中)
    public static void Draw(float x, float y, uint c, string s, bool center = false, int size = 1, uint ink = 0x000000, bool shade = true)
    {
      int dot = Dot(size);
      if (center)
        x -= Width(s, size) / 2f;
      Surf sf = D.Sf;
      int X = (int)Math.Round((x + sf.OX) * D.S), Y = (int)Math.Round((y + sf.OY) * D.S);
      int step = 6 * dot * D.S;
      // 文字の色: 上が少し明るく、下が少し暗い
      int rows = 8 * dot * D.S + 2 * D.S;
      for (int pass = 0; pass < 2; pass++)
        for (int n = 0; n < s.Length; n++)
        {
          int ch = s[n];
          if (ch == ' ')
            continue;
          Glyph g = Get(ch, dot);
          int gx = X + n * step - g.Pad - (dot * D.S) - 0, gy = Y - g.Pad - (dot * D.S);
          bool[] m = pass == 0 ? g.Ink : g.Fill;
          for (int yy = 0; yy < g.H; yy++)
          {
            uint col = ink;
            if (pass == 1)
            {
              col = c;
              if (shade)
              {
                float k = (float)(yy - g.Pad) / rows;
                col = k < 0.5f ? D.Mix(c, 0xffffff, (0.5f - k) * 0.35f) : D.Mul(c, 1 - (k - 0.5f) * 0.45f);
              }
            }
            int run = -1;
            for (int xx = 0; xx <= g.W; xx++)
            {
              bool on = xx < g.W && m[yy * g.W + xx];
              if (on && run < 0)
                run = xx;
              else if (!on && run >= 0)
              {
                D.SpanPx(gx + run, gx + xx - 1, gy + yy, col, 255);
                run = -1;
              }
            }
          }
        }
    }

